// Gesture state and anchor geometry in jsdom; not physical-device validation.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { JSDOM } from 'jsdom';
await mkdir('.cache/editor-gestures', { recursive: true });
await writeFile('.cache/editor-gestures/gestures.mjs', ts.transpileModule(await readFile('lib/editor-gestures.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText);
const { installEditorGestures } = await import('../.cache/editor-gestures/gestures.mjs');
const dom = new JSDOM('<div id="viewport"><div id="content"><div id="page"><button>Text</button></div></div></div>');
globalThis.Event = dom.window.Event;
globalThis.requestAnimationFrame = fn => setTimeout(fn, 0);
globalThis.cancelAnimationFrame = clearTimeout;
const doc = dom.window.document, viewport = doc.getElementById('viewport'), content = doc.getElementById('content'), page = doc.getElementById('page');
let zoom = 100, changes = [], starts = 0, clicks = 0;
viewport.scrollLeft = 0; viewport.scrollTop = 70;
Object.defineProperty(viewport, 'clientHeight', { value: 500 });
page.getBoundingClientRect = () => ({ left: 20 + Math.max(0, (360 - 360 * zoom / 100) / 2) - viewport.scrollLeft, top: 80 - viewport.scrollTop, width: 360 * zoom / 100, height: 720 * zoom / 100 });
const dispose = installEditorGestures({ viewport, content, page, getZoom: () => zoom, onZoom: value => { zoom = value; changes.push(value); }, onStart: () => starts++ });
const touch = (identifier, clientX, clientY) => ({ identifier, clientX, clientY });
function send(type, touches) { const e = new dom.window.Event(type, { bubbles: true, cancelable: true }); Object.defineProperty(e, 'touches', { value: touches }); page.dispatchEvent(e); return e; }
const tick = () => new Promise(resolve => setTimeout(resolve, 5));
doc.querySelector('button').addEventListener('click', () => clicks++);
assert.equal(send('touchstart', [touch(1, 100, 160)]).defaultPrevented, false, 'Single finger retains browser scrolling');
assert.equal(starts, 0);
const initial = page.getBoundingClientRect(), anchor = { x: (150 - initial.left) / initial.width, y: (160 - initial.top) / initial.height };
assert(send('touchstart', [touch(1, 100, 160), touch(2, 200, 160)]).defaultPrevented);
send('touchmove', [touch(1, 60, 180), touch(2, 260, 180)]); await tick();
assert.equal(zoom, 100, 'Pinching does not trigger repeated full PDF renders');
assert.match(content.style.transform, /scale\(2\)/);
assert.equal(viewport.dataset.editorGesturing, 'true');
send('touchend', [touch(2, 260, 180)]);
assert.equal(zoom, 200); assert.deepEqual(changes, [200]);
let bounds = page.getBoundingClientRect();
assert(Math.abs(bounds.left + anchor.x * bounds.width - 160) < 0.01, 'Horizontal point stays under moving midpoint');
assert(Math.abs(bounds.top + anchor.y * bounds.height - 180) < 0.01, 'Vertical point stays under moving midpoint');
assert.equal(content.style.transform, '');
assert(send('touchmove', [touch(2, 300, 180)]).defaultPrevented, 'Remaining finger cannot drag an edit');
send('touchend', []);
doc.querySelector('button').dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true, cancelable: true, detail: 1 })); assert.equal(clicks, 0, 'Pinch compatibility click cannot select text');
send('touchstart', [touch(3, 100, 100)]); send('touchend', []);
doc.querySelector('button').dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true, detail: 1 })); assert.equal(clicks, 1, 'Fresh intentional tap works immediately');
send('touchstart', [touch(1, 100, 160), touch(2, 200, 160)]);
send('touchmove', [touch(1, 50, 160), touch(2, 350, 160)]); await tick();
send('touchcancel', []); assert.equal(zoom, 200, 'Cancelled pinch does not change saved zoom'); assert.equal(content.style.transform, '');
send('touchstart', [touch(1, 100, 160), touch(2, 200, 160)]);
send('touchmove', [touch(1, 0, 160), touch(2, 800, 160)]); send('touchend', []); assert.equal(zoom, 400, 'Zoom is bounded');
send('touchstart', [touch(1, 100, 160)]); send('touchmove', [touch(1, 100, 210)]); send('touchend', []);
doc.querySelector('button').dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true, detail: 1 })); assert.equal(clicks, 1, 'A scroll is not a text tap');
const ordinaryWheel = new dom.window.WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: 50 }); page.dispatchEvent(ordinaryWheel); assert(!ordinaryWheel.defaultPrevented);
const wheel = new dom.window.WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: 100, ctrlKey: true, clientX: 170, clientY: 190 }); page.dispatchEvent(wheel); assert(wheel.defaultPrevented); await new Promise(resolve => setTimeout(resolve, 160)); assert(zoom < 400 && zoom > 200);
send('touchstart', [touch(1, 100, 160), touch(2, 200, 160)]); send('touchmove', [touch(1, 0, 160), touch(2, 300, 160)]); dispose(); await tick(); assert.equal(content.style.transform, ''); assert.equal(viewport.dataset.editorGesturing, undefined);
console.log('PASS: anchored pinch, pan, bounded zoom, cancellation, tap/scroll isolation, trackpad zoom and cleanup.');

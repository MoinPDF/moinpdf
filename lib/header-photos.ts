export type HeaderPhoto = (typeof headerPhotos)[number];

export function randomHeaderPhoto(previousSrc: string | null): HeaderPhoto {
  const candidates = headerPhotos.filter((photo) => photo.src !== previousSrc);
  return candidates[Math.floor(Math.random() * candidates.length)];
}

// Regenerate after changing an opted-in useToolDraftState field. No runtime compiler.
import ts from 'typescript';
import { writeFile } from 'node:fs/promises';
const config = ts.readConfigFile('tsconfig.selfhost.json', ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, '.');
const program = ts.createProgram(parsed.fileNames, parsed.options), checker = program.getTypeChecker();
const types = new Map(), definitions = [], fields = new Map();
function schema(type) {
  const f = ts.TypeFlags;
  if (type.flags & f.StringLiteral) return `z.literal(${JSON.stringify(type.value)})`;
  if (type.flags & f.NumberLiteral) return `z.literal(${type.value})`;
  if (type.flags & f.BooleanLiteral) return `z.literal(${type.intrinsicName})`;
  if (type.flags & f.String) return 'z.string().max(1000000)';
  if (type.flags & f.Number) return 'z.number().finite()';
  if (type.flags & f.Boolean) return 'z.boolean()';
  if (type.flags & f.Null) return 'z.null()';
  if (type.flags & f.Undefined) return 'z.undefined()';
  if (type.isUnion()) return `z.union([${type.types.map(schema).join(',')}])`;
  if (checker.isTupleType(type)) return `z.tuple([${checker.getTypeArguments(type).map(schema).join(',')}])`;
  if (checker.isArrayType(type)) return `z.array(${schema(checker.getTypeArguments(type)[0])}).max(100000)`;
  if (!(type.flags & f.Object) && !type.isIntersection()) throw Error('Unsupported draft type: ' + checker.typeToString(type));
  const prior = types.get(type); if (prior) return prior;
  const name = `shape${types.size}`; types.set(type,name);
  const index = checker.getIndexTypeOfType(type,ts.IndexKind.String) || checker.getIndexTypeOfType(type,ts.IndexKind.Number);
  let body;
  if (index) body = `z.record(z.string().max(2000),${schema(index)})`;
  else body = `z.object({${checker.getPropertiesOfType(type).map(p=>{
    const value = schema(checker.getTypeOfSymbolAtLocation(p,p.valueDeclaration||p.declarations[0]));
    return `${JSON.stringify(p.name)}:${value}${p.flags & ts.SymbolFlags.Optional ? '.optional()':''}`;
  }).join(',')}}).strict()`;
  definitions.push(`const ${name}: z.ZodType = z.lazy(() => ${body});`);
  return name;
}
for (const source of program.getSourceFiles()) {
  if (!source.fileName.includes('components/studio/')) continue;
  function visit(n) {
    if (ts.isVariableDeclaration(n) && ts.isArrayBindingPattern(n.name) && n.initializer && ts.isCallExpression(n.initializer) && n.initializer.expression.getText(source)==='useToolDraftState') {
      const call=n.initializer;
      let arg=call.arguments[0]; while(ts.isBinaryExpression(arg)) arg=arg.left;
      if(!ts.isStringLiteral(arg)) throw Error('Draft keys require a literal prefix');
      const name=arg.text.split(':')[0];
      const type=checker.getTypeAtLocation(n.name.elements[0]);
      fields.set(name,schema(type));
    }
    ts.forEachChild(n,visit);
  } visit(source);
}
// Retired control remains accepted when opening pre-photo-detection projects.
fields.set('ScanSplitPanel.gap', 'z.number().finite()');
await writeFile('lib/tool-draft-schema.ts',`// Generated by scripts/generate-tool-draft-schema.mjs from opted-in tool fields.\nimport { z } from 'zod';\n${definitions.join('\n')}\nconst fields: Record<string,z.ZodType> = {${[...fields].map(([k,v])=>JSON.stringify(k)+':'+v).join(',')}};\nexport const toolDraftSchema = z.record(z.string().max(20000), z.unknown()).superRefine((drafts, ctx) => {\n if (Object.keys(drafts).length > 3000 || JSON.stringify(drafts).length > 16000000) {ctx.addIssue({code:'custom',message:'Too many tool drafts'});return;}\n for(const [key,value] of Object.entries(drafts)){const schema=fields[key.split(':')[0]];if(!schema || !schema.safeParse(value).success) ctx.addIssue({code:'custom',path:[key],message:'Invalid tool draft'});}\n});\n`);
console.log(`Generated ${fields.size} draft fields and ${definitions.length} object shapes.`);
